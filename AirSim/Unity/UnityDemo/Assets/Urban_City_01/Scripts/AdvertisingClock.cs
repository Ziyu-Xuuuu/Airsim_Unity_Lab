using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class AdvertisingClock : MonoBehaviour {
//----------------------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------------------
//    
//                                                         Advertising Clock Script
//
//                                                 by Andre "AEG" Bürger of VIS-Games 2023
//
//----------------------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------------------


    Transform rotator;
    float angleRotator;
    public float speedRotator = 10.0f;

    Vector3 angle;
    
    Transform[] handleHours;
    Transform[] handleMinues;
    Transform[] handleSeconds;

    public int testMin = 5;
    public int testHour = 4;

//----------------------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------------------
void Start()
{
    //-----------------------------------------------------------------
    rotator = transform.Find("rotator");
    angleRotator = Random.Range(0.0f, 360.0f);
    //-----------------------------------------------------------------
    handleHours = new Transform[4];
    handleMinues = new Transform[4];
    handleSeconds = new Transform[4];

    handleHours[0] = transform.Find("clock_01/handle_hour");
    handleMinues[0] = transform.Find("clock_01/handle_minutes");
    handleSeconds[0] = transform.Find("clock_01/handle_seconds");

    handleHours[1] = transform.Find("clock_02/handle_hour");
    handleMinues[1] = transform.Find("clock_02/handle_minutes");
    handleSeconds[1] = transform.Find("clock_02/handle_seconds");

    handleHours[2] = transform.Find("clock_03/handle_hour");
    handleMinues[2] = transform.Find("clock_03/handle_minutes");
    handleSeconds[2] = transform.Find("clock_03/handle_seconds");

    handleHours[3] = transform.Find("clock_04/handle_hour");
    handleMinues[3] = transform.Find("clock_04/handle_minutes");
    handleSeconds[3] = transform.Find("clock_04/handle_seconds");
    //-----------------------------------------------------------------
    
}
//----------------------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------------------
void Update()
{
    //-----------------------------------------------------------------
    angleRotator += Time.deltaTime * speedRotator;
    if(angleRotator >= 360.0f)
        angleRotator -= 360.0f;
    angle.x = 0.0f;
    angle.z = 0.0f;
    angle.y = angleRotator;
    rotator.transform.localEulerAngles = angle;
    //-----------------------------------------------------------------
    int i;
    for(i=0;i<4;i++)
    {
        angle.x = 0.0f;
        angle.y = 0.0f;

        angle.z = (float)((360 / 60) * System.DateTime.Now.Second);
        handleSeconds[i].localEulerAngles = angle;        

        angle.z = (float) ((360 / 60) * System.DateTime.Now.Minute);
        handleMinues[i].localEulerAngles = angle;        
   
        angle.z = (float) ( ((360 / 12) * System.DateTime.Now.Hour) + ((30 * System.DateTime.Now.Minute) / 60) );
        handleHours[i].localEulerAngles = angle;        
    }
    //-----------------------------------------------------------------

}
//----------------------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------------------------------------------------------------
}
